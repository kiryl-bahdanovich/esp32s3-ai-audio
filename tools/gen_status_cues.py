#!/usr/bin/env python3
"""Generate pre-rendered PCM status cues for the ESP32 AI assistant.

Calls OpenAI TTS (gpt-4o-mini-tts, voice marin, response_format=pcm) and
writes src/status_cues_data.cpp with PCM16 mono @ 24 kHz byte arrays.

Usage (from ai-assistant/):

  export OPENAI_API_KEY=sk-...   # or pass --secrets src/secrets.h
  python3 tools/gen_status_cues.py

Never commit secrets.h or print the API key.
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

CUES = [
    ("WifiConnected", "WiFi connected"),
    ("YouCanSpeakNow", "You can speak now"),
]

TTS_URL = "https://api.openai.com/v1/audio/speech"
TTS_MODEL = "gpt-4o-mini-tts"
TTS_VOICE = "marin"


def extract_api_key_from_secrets(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    m = re.search(r'OPENAI_API_KEY\s*=\s*"([^"]+)"', text)
    if not m:
        raise SystemExit(f"OPENAI_API_KEY not found in {path}")
    return m.group(1)


def synthesize(api_key: str, phrase: str) -> bytes:
    import json

    body = json.dumps(
        {
            "model": TTS_MODEL,
            "voice": TTS_VOICE,
            "input": phrase,
            "response_format": "pcm",
        }
    ).encode("utf-8")
    req = urllib.request.Request(
        TTS_URL,
        data=body,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            return resp.read()
    except urllib.error.HTTPError as e:
        detail = e.read().decode("utf-8", errors="replace")
        raise SystemExit(f"TTS HTTP {e.code} for {phrase!r}: {detail}") from e


def emit_array(name: str, phrase: str, pcm: bytes) -> str:
    lines = [
        f"// \"{phrase}\" — {TTS_MODEL}, voice {TTS_VOICE}, PCM16 mono @ 24 kHz",
        f"static const uint8_t k{name}Data[] = {{",
    ]
    for i in range(0, len(pcm), 16):
        chunk = pcm[i : i + 16]
        hexes = ", ".join(f"0x{b:02x}" for b in chunk)
        comma = "," if i + 16 < len(pcm) else ""
        lines.append(f"    {hexes}{comma}")
    lines.append("};")
    lines.append(f"static const size_t k{name}Bytes = sizeof(k{name}Data);")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parents[1]
    parser.add_argument(
        "--secrets",
        type=Path,
        default=root / "src" / "secrets.h",
        help="Path to secrets.h (used if OPENAI_API_KEY env is unset)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=root / "src" / "status_cues_data.cpp",
        help="Output C++ file with embedded PCM arrays",
    )
    args = parser.parse_args()

    import os

    api_key = os.environ.get("OPENAI_API_KEY", "").strip()
    if not api_key:
        api_key = extract_api_key_from_secrets(args.secrets)

    arrays = []
    for cue_id, phrase in CUES:
        print(f"TTS: {cue_id} ({len(phrase)} chars)…", file=sys.stderr)
        pcm = synthesize(api_key, phrase)
        if len(pcm) < 2 or len(pcm) % 2 != 0:
            raise SystemExit(f"Unexpected PCM size {len(pcm)} for {cue_id}")
        print(f"  -> {len(pcm)} bytes ({len(pcm) / 48000:.2f}s @ 24 kHz)", file=sys.stderr)
        arrays.append(emit_array(cue_id, phrase, pcm))

    header = """\
// Auto-generated by tools/gen_status_cues.py — do not edit by hand.
// Regenerate: python3 tools/gen_status_cues.py

#include "status_cues.h"

#include "audio_out.h"

#include <cstddef>
#include <cstdint>

namespace status_cues
{
namespace
{

"""
    footer_parts = [
        "} // namespace\n",
        "\n",
        "void play(Cue cue)\n",
        "{\n",
        "    const uint8_t *bytes = nullptr;\n",
        "    size_t byteCount = 0;\n",
        "    switch (cue)\n",
        "    {\n",
    ]
    for cue_id, _ in CUES:
        footer_parts.append(f"    case Cue::{cue_id}:\n")
        footer_parts.append(f"        bytes = k{cue_id}Data;\n")
        footer_parts.append(f"        byteCount = k{cue_id}Bytes;\n")
        footer_parts.append("        break;\n")
    footer_parts.append(
        """\
    }
    if (bytes == nullptr || byteCount < sizeof(int16_t))
    {
        return;
    }
    audio_out::enqueuePcm16Mono(
        reinterpret_cast<const int16_t *>(bytes), byteCount / sizeof(int16_t));
}

} // namespace status_cues
"""
    )

    out_text = header + "\n".join(arrays) + "".join(footer_parts)
    args.out.write_text(out_text, encoding="utf-8")
    print(f"Wrote {args.out} ({args.out.stat().st_size} bytes)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
